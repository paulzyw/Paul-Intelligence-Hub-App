const COUNTRY_ALIAS_MAP: Record<string, string> = {
  usa: 'United States',
  us: 'United States',
  'u.s.': 'United States',
  'u.s.a.': 'United States',
  uk: 'United Kingdom',
  'u.k.': 'United Kingdom',
  'great britain': 'United Kingdom',
  uae: 'United Arab Emirates',
  'south korea': 'South Korea',
  korea: 'South Korea',
  prc: 'China'
};

export function matchStandardCountry(raw?: string): string {
  if (!raw) return '';
  const trimmed = raw.trim();
  if (!trimmed) return '';
  const lower = trimmed.toLowerCase();
  if (COUNTRY_ALIAS_MAP[lower]) return COUNTRY_ALIAS_MAP[lower];
  const exact = STANDARD_COUNTRIES.find((c) => c.toLowerCase() === lower);
  return exact || '';
}

export function parseLegacyLocationToCountryAndState(location?: string): {
  country: string;
  state_province: string;
} {
  if (!location || !location.trim()) {
    return { country: '', state_province: '' };
  }
  const trimmed = location.trim();
  const directCountry = matchStandardCountry(trimmed);
  if (directCountry) {
    return { country: directCountry, state_province: '' };
  }
  const parts = trimmed.split(',').map((p) => p.trim()).filter(Boolean);
  if (parts.length >= 2) {
    const lastPart = parts[parts.length - 1];
    const matchedLast = matchStandardCountry(lastPart);
    if (matchedLast) {
      return {
        country: matchedLast,
        state_province: parts.slice(0, -1).join(', ')
      };
    }
  }
  return { country: '', state_province: trimmed };
}
