const sanitizeIdList = (arr: any, allowedSet: Set<string>): string[] => {
  if (!Array.isArray(arr)) return [];
  const unique = new Set<string>();
  arr.forEach((raw: any) => {
    const val = String(raw || '').trim();
    if (val && allowedSet.has(val)) {
      unique.add(val);
    }
  });
  return Array.from(unique);
};

